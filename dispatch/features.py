"""What the desk knows about a request when it quotes: the inputs of the learned cost model (fee model 3).

One function, `features(request, desk)`, serves both sides: the training script (tracks/ml/rows.py)
replays saved weeks through a desk and calls it at each request's arrival, and `Fees` calls it at
quote time. Nothing in it happens after the quote. The model itself is `dispatch/learned.py`,
generated by tracks/ml/train.py.
"""
from __future__ import annotations

from typing import TYPE_CHECKING, Any

from .towns import DELIVERY

if TYPE_CHECKING:
    from .desk import Desk

HOUR, DAY = 60, 24 * 60

NAMES = (
    # the lane
    "pickup_lat", "pickup_lon", "delivery_lat", "delivery_lon", "km", "minutes", "straight_km",
    "pickup_30", "pickup_80", "delivery_30", "delivery_80", "lane_part",
    # the time
    "weekday", "minute", "lead_h", "slack_min_h", "slack_max_h", "nights", "weekend",
    # the cars and the note
    "legs", "typical_eur", "private_pickup", "private_delivery", "electric_low", "premium",
    "manual", "plates", "note", "note_ready_h", "note_deadline", "note_unsure", "pickup_open_h", "delivery_open_h",
    # the options
    "options", "same_day", "next_day",
    # our own state at quote time
    "unbooked", "open_gigs", "held", "booked_near", "fits", "bundles_on",
    # our own fee schedule for the car: its opening and its cap, as multiples of the typical fee
    "sched_open", "sched_cap",
)


def near(desk: "Desk", place: str) -> tuple[int, int]:
    """The drivers living within 30 km and within 80 km of a place (straight line), cached on the context."""
    ctx = desk.ctx
    cache = ctx.__dict__.setdefault("_near", {})
    if place not in cache:
        km = [ctx.straight_km(place, driver["homePlaceId"]) for driver in ctx.roster]
        cache[place] = (sum(k <= 30 for k in km), sum(k <= 80 for k in km))
    return cache[place]


def schedule_features(request: dict[str, Any], desk: "Desk") -> tuple[float, float]:
    """The opening and the cap of the fee schedule that the desk's fees part would give the request's car
    alone, as multiples of its typical fee. Training rows take the same two numbers from the car's
    first posted gig (tracks/ml/rows.py)."""
    fees = desk.parts.fees
    legs = request["legs"]
    deadline = max(option["deadline"] for option in request["options"])
    leg = legs[0]
    drive = desk.ctx.minutes(leg["pickup"]["placeId"], leg["delivery"]["placeId"])
    order = {"id": request["id"], "legs": legs, "deadline": deadline, "lastPickupAt": deadline - drive,
             "priceCents": request["options"][0]["listPriceCents"], "deliveredAt": [None] * len(legs)}
    known = request["id"] in desk.requests
    desk.requests.setdefault(request["id"], request)
    try:
        schedule = fees.schedule(order, 1, False, desk)
    finally:
        if not known:
            desk.requests.pop(request["id"], None)
    typical = request["referenceFeeCents"] / len(legs)
    return schedule[0]["feeCents"] / typical, max(step["feeCents"] for step in schedule) / typical


def state(request: dict[str, Any], desk: "Desk") -> list[float]:
    """Our own books at quote time: orders without a driver, our open gigs, orders held, our booked gigs
    that end near the pickup, and whether the car could join a gig that is open now."""
    from .intake import unbooked
    pickup = request["legs"][0]["pickup"]["placeId"]
    carried = {gig for legs in desk.leg_gigs.values() for gig in legs.values()}
    open_gigs = sum(1 for gig in carried if gig not in desk.booked)
    held = sum(1 for order in desk.orders.values() if any(at is None for at in order["deliveredAt"]))
    booked_near = 0
    for gig in carried:
        if gig in desk.booked and gig in desk.posts:
            last = desk.posts[gig]["stops"][-1]
            order = desk.orders.get(last["orderId"])
            if order is not None and desk.ctx.straight_km(order["legs"][last["leg"]]["delivery"]["placeId"], pickup) <= 50:
                booked_near += 1
    bundles = desk.parts.bundles
    fits = float(bool(bundles) and bundles.fits(request, desk))
    return [unbooked(desk), open_gigs, held, booked_near, fits, float(bool(bundles))]


def features(request: dict[str, Any], desk: "Desk", schedule: tuple[float, float] | None = None) -> list[float]:
    """The request's features, in the order of `NAMES`. `schedule` overrides the fee schedule features
    (the training rows pass the schedule the car really got)."""
    ctx = desk.ctx
    legs = request["legs"]
    leg = legs[0]
    pickup, delivery = leg["pickup"], leg["delivery"]
    p, d = ctx.places[pickup["placeId"]], ctx.places[delivery["placeId"]]
    km, minutes = ctx.km(pickup["placeId"], delivery["placeId"]), ctx.minutes(pickup["placeId"], delivery["placeId"])
    arrived = request["arrivedAt"]
    notes = desk.parts.notes
    facts = notes.facts(request) if hasattr(notes, "facts") else None
    earliest = max(pickup["window"]["from"], (facts.ready or 0) if facts else 0, arrived)
    deadlines = [option["deadline"] for option in request["options"]]
    kinds = {option["kind"] for option in request["options"]}
    first_day, last_day = earliest // DAY, max(deadlines) // DAY
    weekend = any(day % 7 >= 5 for day in range(first_day, last_day + 1))
    hours = lambda place: (place["hours"]["closes"] - place["hours"]["opens"]) / HOUR if place.get("hours") and not place["privateAddress"] else 24.0
    note_deadline = float(bool(facts and facts.deadline and facts.deadline < max(deadlines)))
    lane = [p["lat"], p["lon"], d["lat"], d["lon"], km, minutes, ctx.straight_km(pickup["placeId"], delivery["placeId"]),
            *near(desk, pickup["placeId"]), *near(desk, delivery["placeId"]), DELIVERY.get(delivery["placeId"], 0.0)]
    time = [arrived // DAY, arrived % DAY, (earliest - arrived) / HOUR, (min(deadlines) - earliest - minutes) / HOUR,
            (max(deadlines) - earliest - minutes) / HOUR, last_day - first_day, float(weekend)]
    cars = [len(legs), request["referenceFeeCents"] / 100,
            float(any(l["pickup"]["privateAddress"] for l in legs)), float(any(l["delivery"]["privateAddress"] for l in legs)),
            float(any(l["car"]["electric"] and (l["car"]["chargePercent"] or 0) < 30 for l in legs)),
            float(any(l["car"]["premium"] for l in legs)),
            float(bool(facts and facts.manual)), float(bool(facts and facts.plates)), float(bool(request.get("note"))),
            ((facts.ready - arrived) / HOUR) if facts and facts.ready else -1.0, note_deadline,
            float(bool(facts and not facts.sure)), hours(pickup), hours(delivery)]
    options = [len(deadlines), float("same_day" in kinds), float("next_day" in kinds)]
    return lane + time + cars + options + state(request, desk) + list(schedule or schedule_features(request, desk))
